using System.Buffers.Binary;
using System.IO.Compression;
using System.Text;

namespace PlcInfo.Parsing;

/// <summary>
/// Reads the outer container of a Rockwell Studio 5000 / RSLogix 5000 <c>.ACD</c> project file.
/// </summary>
/// <remarks>
/// Layout (reverse-engineered by hutcheb/acd, confirmed against v30 and v34 files):
/// <list type="bullet">
/// <item>Member files are stored back to back from offset 0. The first member is the
/// plain-text <c>Version.Log</c>, so the file starts with CR LF and the text
/// "This file was generated by the RSLogix 5000 software". Only the product-neutral
/// prefix is checked, in case later releases change the product name.</item>
/// <item>The last 8 bytes are two little-endian <c>uint32</c>: the member count and an
/// unknown value.</item>
/// <item>Immediately before that trailer is a directory of one 528-byte entry per member:
/// a NUL-terminated UTF-16LE name padded to 520 bytes, then <c>uint32</c> length and
/// <c>uint32</c> offset.</item>
/// <item>Members that start with the gzip magic (1F 8B) are gzip-compressed
/// (e.g. <c>QuickInfo.XML</c>, <c>TagInfo.XML</c>, <c>Comps.Dat</c>); others are stored raw.</item>
/// </list>
/// </remarks>
internal sealed class RockwellAcdContainer
{
    private const int DirectoryEntrySize = 528;
    private const int NameFieldSize = 520;
    private const int TrailerSize = 8;

    /// <summary>Upper bound for one decompressed member, to stop decompression bombs.</summary>
    internal const long MaxDecompressedMemberBytes = 512L * 1024 * 1024;

    private static readonly byte[] Signature = "\r\nThis file was generated by the "u8.ToArray();

    private readonly string _filePath;
    private readonly Dictionary<string, (long Offset, long Length)> _members;

    private RockwellAcdContainer(string filePath, Dictionary<string, (long Offset, long Length)> members, IReadOnlyList<string> memberNames)
    {
        _filePath = filePath;
        _members = members;
        MemberNames = memberNames;
    }

    /// <summary>Member file names in directory order.</summary>
    public IReadOnlyList<string> MemberNames { get; }

    /// <summary>
    /// Opens and validates the container. Throws <see cref="InvalidOperationException"/>
    /// when the file is not an ACD project.
    /// </summary>
    public static RockwellAcdContainer Open(string filePath)
    {
        using var stream = File.OpenRead(filePath);
        long size = stream.Length;

        if (size < Signature.Length + TrailerSize)
            throw NotAnAcd(filePath, "the file is too small");

        var head = new byte[Signature.Length];
        stream.ReadExactly(head);
        if (!head.AsSpan().SequenceEqual(Signature))
            throw NotAnAcd(filePath, "the RSLogix 5000 version header is missing");

        var trailer = new byte[TrailerSize];
        stream.Seek(size - TrailerSize, SeekOrigin.Begin);
        stream.ReadExactly(trailer);
        uint count = BinaryPrimitives.ReadUInt32LittleEndian(trailer);

        long directoryOffset = size - TrailerSize - (long)count * DirectoryEntrySize;
        if (count == 0 || directoryOffset < 0)
            throw NotAnAcd(filePath, "the member directory is invalid");

        var directory = new byte[count * DirectoryEntrySize];
        stream.Seek(directoryOffset, SeekOrigin.Begin);
        stream.ReadExactly(directory);

        var members = new Dictionary<string, (long, long)>(StringComparer.OrdinalIgnoreCase);
        var names = new List<string>();
        for (int i = 0; i < count; i++)
        {
            var entry = directory.AsSpan(i * DirectoryEntrySize, DirectoryEntrySize);
            var name = ReadUtf16Z(entry[..NameFieldSize]);
            uint length = BinaryPrimitives.ReadUInt32LittleEndian(entry[NameFieldSize..]);
            uint offset = BinaryPrimitives.ReadUInt32LittleEndian(entry[(NameFieldSize + 4)..]);

            if (name.Length == 0 || (long)offset + length > directoryOffset)
                throw NotAnAcd(filePath, $"directory entry {i} is out of range");

            names.Add(name);
            members.TryAdd(name, (offset, length));
        }

        if (!members.ContainsKey("Version.Log"))
            throw NotAnAcd(filePath, "Version.Log is missing");

        return new RockwellAcdContainer(filePath, members, names);
    }

    /// <summary>Returns true if the container has a member with this name.</summary>
    public bool Contains(string name) => _members.ContainsKey(name);

    /// <summary>
    /// Returns the member's bytes, decompressed if it is gzip-compressed,
    /// or null if the container has no such member.
    /// </summary>
    public byte[]? ReadMember(string name)
    {
        if (!_members.TryGetValue(name, out var location))
            return null;

        using var stream = File.OpenRead(_filePath);
        stream.Seek(location.Offset, SeekOrigin.Begin);
        var raw = new byte[location.Length];
        stream.ReadExactly(raw);

        if (raw.Length < 2 || raw[0] != 0x1F || raw[1] != 0x8B)
            return raw;

        using var gzip = new GZipStream(new MemoryStream(raw), CompressionMode.Decompress);
        using var output = new MemoryStream();
        var buffer = new byte[81920];
        int read;
        while ((read = gzip.Read(buffer, 0, buffer.Length)) > 0)
        {
            if (output.Length + read > MaxDecompressedMemberBytes)
                throw new InvalidOperationException(
                    $"ACD member '{name}' decompresses to more than {MaxDecompressedMemberBytes / (1024 * 1024)} MB; refusing to continue.");
            output.Write(buffer, 0, read);
        }
        return output.ToArray();
    }

    private static string ReadUtf16Z(ReadOnlySpan<byte> field)
    {
        int end = 0;
        while (end + 1 < field.Length && (field[end] != 0 || field[end + 1] != 0))
            end += 2;
        return Encoding.Unicode.GetString(field[..end]);
    }

    private static InvalidOperationException NotAnAcd(string filePath, string reason) =>
        new($"'{Path.GetFileName(filePath)}' is not a valid Rockwell ACD project file ({reason}). " +
            "Open it in Studio 5000 and export it to L5X (File > Save As > .L5X), then parse the L5X.");
}
