using System.IO.Compression;
using System.Text;
using FluentAssertions;
using PlcInfo.Parsing;
using Xunit.Categories;

namespace PlcInfo.Tests.Parsing;

[UnitTest]
public class RockwellAcdParserTests : IDisposable
{
    private readonly RockwellAcdParser _parser = new();
    private readonly List<string> _files = new();

    public void Dispose()
    {
        foreach (var file in _files)
        {
            if (File.Exists(file))
                File.Delete(file);
        }
    }

    [Theory]
    [InlineData("test.ACD", true)]
    [InlineData("test.acd", true)]
    [InlineData("test.Acd", true)]
    [InlineData("test.L5X", false)]
    [InlineData("test.xml", false)]
    [InlineData("test.txt", false)]
    public void CanParse_WithVariousExtensions_ReturnsExpectedResult(string filename, bool expected)
    {
        _parser.CanParse(filename).Should().Be(expected);
    }

    [Fact]
    public async Task ParseAsync_WithNonExistentFile_ThrowsFileNotFoundException()
    {
        var nonExistentFile = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"), "file.acd");

        var action = async () => await _parser.ParseAsync(nonExistentFile);

        await action.Should().ThrowAsync<FileNotFoundException>()
            .WithMessage($"File not found: {nonExistentFile}");
    }

    [Theory]
    [InlineData(new byte[] { 0x50, 0x4B, 0x03, 0x04 })] // ZIP header: ACDs are not ZIP files
    [InlineData(new byte[] { })]
    public async Task ParseAsync_WithNonAcdBytes_ThrowsInvalidOperationException(byte[] content)
    {
        var path = WriteFile(content);

        var action = async () => await _parser.ParseAsync(path);

        await action.Should().ThrowAsync<InvalidOperationException>()
            .WithMessage("*is not a valid Rockwell ACD project file*export it to L5X*");
    }

    [Fact]
    public async Task ParseAsync_WithVersionHeaderButNoDirectory_ThrowsInvalidOperationException()
    {
        var text = "\r\nThis file was generated by the RSLogix 5000 software.\r\n\r\nDO NOT ALTER THIS FILE\r\n";
        var bytes = Encoding.ASCII.GetBytes(text).Concat(new byte[] { 0xFF, 0xFF, 0xFF, 0x7F, 0, 0, 0, 0 }).ToArray();
        var path = WriteFile(bytes);

        var action = async () => await _parser.ParseAsync(path);

        await action.Should().ThrowAsync<InvalidOperationException>()
            .WithMessage("*member directory is invalid*");
    }

    [Fact]
    public async Task ParseAsync_WithOnlyXmlMembers_ReturnsPartialProjectFromXml()
    {
        // A container with the version log and the two compressed XML indexes, but no
        // binary component database.
        var path = WriteFile(BuildContainer(
            ("Version.Log", Encoding.ASCII.GetBytes(
                "\r\nThis file was generated by the RSLogix 5000 software.\r\n\r\n" +
                "2024-01-02 03:04:05.678: File Creation\r\n" +
                "2024-01-02 03:04:06.000: Saved - V33.00.00/3500.002\r\n"), false),
            ("QuickInfo.XML", Utf16Xml(
                "<LogixQuickInfo Name=\"Line1\"><SWVersion String=\"RSLogix 5000 v33.00\"/>" +
                "<DeviceIdentity VendorID=\"1\" ProductType=\"14\" ProductCode=\"166\" MajorRevision=\"33\" MinorRevision=\"11\"/>" +
                "<ControllerSlot SlotNumber=\"2\"/></LogixQuickInfo>"), true),
            ("TagInfo.XML", Utf16Xml(
                "<LogixTagInfo Name=\"Line1\"><Tags>" +
                "<Tag Name=\"Speed\" DataType=\"REAL\" ExtAcc=\"Read/Write\"><Description>\n  Line speed\n </Description></Tag>" +
                "<Tag Name=\"Buffer\" DataType=\"DINT\"><Dimensions><Dim Size=\"10\"/></Dimensions></Tag>" +
                "</Tags><Programs><Program Name=\"Main\"><Tags><Tag Name=\"Step\" DataType=\"INT\"/></Tags></Program></Programs>" +
                "</LogixTagInfo>"), true)));

        var project = await _parser.ParseAsync(path);

        project.Format.Should().Be("ACD");
        project.Vendor.Should().Be("Rockwell Automation");
        project.Controller!.Name.Should().Be("Line1");
        project.Controller.Type.Should().Be("1756-L83E");
        project.Controller.FirmwareRevision.Should().Be("33.11");
        project.Controller.Slot.Should().Be(2);
        project.Metadata["ParseStatus"].Should().Be("Partial");
        project.Metadata["SoftwareRevision"].Should().Be("33.00");
        project.Metadata["LastSavedBuild"].Should().Be("V33.00.00/3500.002");

        var warnings = project.Metadata["Warnings"].Split('\n');
        warnings[0].Should().Be(RockwellAcdParser.PartialSupportWarning);
        warnings.Should().Contain(w => w.Contains("no Comps.Dat"));

        project.Tags.Select(t => (t.Name, t.DataType, t.Description)).Should().Equal(
            ("Buffer", "DINT", (string?)null),
            ("Speed", "REAL", "Line speed"));
        project.Tags[0].ArrayDimensions.Should().Equal(10);
        project.Tags[1].Properties["ExternalAccess"].Should().Be("Read/Write");

        // Without the component database, programs come from TagInfo.XML only.
        var program = project.Programs.Should().ContainSingle().Subject;
        program.Name.Should().Be("Main");
        program.Routines.Should().BeEmpty();
        program.LocalTags.Select(t => (t.Name, t.Scope)).Should().Equal(("Step", "Main"));
    }

    [Fact]
    public async Task ParseAsync_WithCorruptComponentDatabase_KeepsXmlDataAndWarns()
    {
        var path = WriteFile(BuildContainer(
            ("Version.Log", Encoding.ASCII.GetBytes("\r\nThis file was generated by the RSLogix 5000 software.\r\n"), false),
            ("QuickInfo.XML", Utf16Xml("<LogixQuickInfo Name=\"C1\"/>"), true),
            ("Comps.Dat", new byte[64], true)));

        var project = await _parser.ParseAsync(path);

        project.Controller!.Name.Should().Be("C1");
        project.Metadata["Warnings"].Should().Contain("component database could not be decoded");
    }

    [Fact]
    public async Task ParseAsync_WithNoControllerInformation_Throws()
    {
        var path = WriteFile(BuildContainer(
            ("Version.Log", Encoding.ASCII.GetBytes("\r\nThis file was generated by the RSLogix 5000 software.\r\n"), false)));

        var action = async () => await _parser.ParseAsync(path);

        await action.Should().ThrowAsync<InvalidOperationException>()
            .WithMessage("*controller information could not be read*L5X*");
    }

    [Fact]
    public async Task ParseAsync_WithDtdInEmbeddedXml_DoesNotProcessIt()
    {
        var path = WriteFile(BuildContainer(
            ("Version.Log", Encoding.ASCII.GetBytes("\r\nThis file was generated by the RSLogix 5000 software.\r\n"), false),
            ("QuickInfo.XML", Utf16Xml("<!DOCTYPE x [<!ENTITY e \"boom\">]><LogixQuickInfo Name=\"&e;\"/>"), true),
            ("TagInfo.XML", Utf16Xml("<LogixTagInfo Name=\"Safe\"/>"), true)));

        var project = await _parser.ParseAsync(path);

        project.Controller!.Name.Should().Be("Safe");
        project.Metadata["Warnings"].Should().Contain("QuickInfo.XML in the ACD is not valid XML");
    }

    private string WriteFile(byte[] content)
    {
        var path = Path.Combine(Path.GetTempPath(), $"plcinfo-acd-{Guid.NewGuid():N}.ACD");
        File.WriteAllBytes(path, content);
        _files.Add(path);
        return path;
    }

    private static byte[] Utf16Xml(string body) =>
        Encoding.Unicode.GetPreamble().Concat(Encoding.Unicode.GetBytes("<?xml version=\"1.0\" encoding=\"UTF-16\"?>" + body)).ToArray();

    /// <summary>
    /// Builds an ACD container: members back to back, a directory of 528-byte entries
    /// (UTF-16 name padded to 520 bytes, length, offset), then member count and an unknown u32.
    /// </summary>
    private static byte[] BuildContainer(params (string Name, byte[] Content, bool Compress)[] members)
    {
        using var output = new MemoryStream();
        var directory = new List<(string Name, int Length, int Offset)>();
        foreach (var (name, content, compress) in members)
        {
            var data = content;
            if (compress)
            {
                using var buffer = new MemoryStream();
                using (var gzip = new GZipStream(buffer, CompressionLevel.Optimal, leaveOpen: true))
                    gzip.Write(content);
                data = buffer.ToArray();
            }
            directory.Add((name, data.Length, (int)output.Length));
            output.Write(data);
        }

        using var writer = new BinaryWriter(output, Encoding.Unicode, leaveOpen: true);
        foreach (var (name, length, offset) in directory)
        {
            var nameBytes = new byte[520];
            Encoding.Unicode.GetBytes(name).CopyTo(nameBytes, 0);
            writer.Write(nameBytes);
            writer.Write(length);
            writer.Write(offset);
        }
        writer.Write(directory.Count);
        writer.Write(0);
        writer.Flush();
        return output.ToArray();
    }
}
